const messagesDir = path.join(__dirname, '..', 'messages');

for (const [lang, data] of Object.entries(translations)) {
  const filePath = path.join(messagesDir, `${lang}.json`);
  let raw = fs.readFileSync(filePath, 'utf8');
  let hasBOM = raw.charCodeAt(0) === 0xFEFF;
  if (hasBOM) raw = raw.slice(1);
  const parsed = JSON.parse(raw);

  parsed.work = parsed.work || {};
  Object.assign(parsed.work, data);

  const output = (hasBOM ? '\uFEFF' : '') + JSON.stringify(parsed, null, 2) + '\n';
  fs.writeFileSync(filePath, output, 'utf8');
  console.log(`Updated messages/${lang}.json`);
}
